function initialLanguage(): Language {
  if (typeof window !== "undefined") {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "zh-CN" || stored === "en-US") {
      return stored;
    }
    return navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
  }
  return "zh-CN";
}

function interpolate(value: string, params?: TranslationParams): string {
  if (!params) {
    return value;
  }
  return Object.entries(params).reduce(
    (result, [key, replacement]) => result.split(`{${key}}`).join(String(replacement)),
    value
  );
}

export function translate(language: Language, key: string, params?: TranslationParams): string {
  const value = messages[language][key] ?? messages["en-US"][key] ?? key;
  return interpolate(value, params);
}

type I18nContextValue = {
  language: Language;
  setLanguage(language: Language): void;
  t(key: string, params?: TranslationParams): string;
};

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, language);
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, params) => translate(language, key, params)
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}
